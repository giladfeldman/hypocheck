// Regenerate the src/hypothesis/example-*.data.ts modules from their example-*.json files.
// The JSON files are canonical; the .ts modules exist so the library needs no JSON-module import
// support. tests/core.test.ts checks they agree.
import fs from "node:fs";

const EXAMPLES = [
  ["example-confbias", "CONFBIAS_EXAMPLE_DATA"],
  ["example-dissonance", "DISSONANCE_EXAMPLE_DATA"],
];
for (const [file, name] of EXAMPLES) {
  const json = fs.readFileSync(new URL(`../src/hypothesis/${file}.json`, import.meta.url), "utf8");
  const data = JSON.parse(json);
  const out =
    `// GENERATED by scripts/build-example-data.mjs from ${file}.json. Do not edit.\n` +
    `export const ${name}: unknown = ${JSON.stringify(data, null, 2)};\n`;
  fs.writeFileSync(new URL(`../src/hypothesis/${file}.data.ts`, import.meta.url), out);
  console.log(`wrote src/hypothesis/${file}.data.ts`);
}
